function trendPoint(
  date: string,
  clicks: number,
  impressions: number,
  sessions: number,
  users: number,
): LiveDashboardData["trend"][number] {
  return {
    date,
    clicks,
    impressions,
    ctr: clicks / impressions,
    position: Number((8.6 - clicks / 90).toFixed(1)),
    sessions,
    users,
  };
}

