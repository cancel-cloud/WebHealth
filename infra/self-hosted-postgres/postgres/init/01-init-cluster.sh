#!/usr/bin/env bash
set -euo pipefail

required_vars=(
  POSTGRES_DB
  POSTGRES_USER
  POSTGRES_RUNTIME_USER
  POSTGRES_RUNTIME_PASSWORD
  POSTGRES_DIRECT_USER
  POSTGRES_DIRECT_PASSWORD
  POSTGRES_REPLICATION_USER
  POSTGRES_REPLICATION_PASSWORD
  POSTGRES_MONITORING_USER
  POSTGRES_MONITORING_PASSWORD
)

for var_name in "${required_vars[@]}"; do
  if [[ -z "${!var_name:-}" ]]; then
    echo "missing required env: ${var_name}" >&2
    exit 1
  fi
done

psql -v ON_ERROR_STOP=1 --username "$POSTGRES_USER" --dbname postgres <<SQL
DO \$\$
BEGIN
  IF NOT EXISTS (SELECT 1 FROM pg_roles WHERE rolname = '${POSTGRES_RUNTIME_USER}') THEN
    EXECUTE format('CREATE ROLE %I LOGIN PASSWORD %L', '${POSTGRES_RUNTIME_USER}', '${POSTGRES_RUNTIME_PASSWORD}');
  END IF;

  IF NOT EXISTS (SELECT 1 FROM pg_roles WHERE rolname = '${POSTGRES_DIRECT_USER}') THEN
    EXECUTE format('CREATE ROLE %I LOGIN PASSWORD %L', '${POSTGRES_DIRECT_USER}', '${POSTGRES_DIRECT_PASSWORD}');
  END IF;

  IF NOT EXISTS (SELECT 1 FROM pg_roles WHERE rolname = '${POSTGRES_REPLICATION_USER}') THEN
    EXECUTE format('CREATE ROLE %I LOGIN REPLICATION PASSWORD %L', '${POSTGRES_REPLICATION_USER}', '${POSTGRES_REPLICATION_PASSWORD}');
  END IF;

  IF NOT EXISTS (SELECT 1 FROM pg_roles WHERE rolname = '${POSTGRES_MONITORING_USER}') THEN
    EXECUTE format('CREATE ROLE %I LOGIN PASSWORD %L', '${POSTGRES_MONITORING_USER}', '${POSTGRES_MONITORING_PASSWORD}');
  END IF;
END
\$\$;

ALTER DATABASE "${POSTGRES_DB}" OWNER TO "${POSTGRES_DIRECT_USER}";
GRANT pg_monitor TO "${POSTGRES_MONITORING_USER}";
GRANT CONNECT ON DATABASE "${POSTGRES_DB}" TO "${POSTGRES_RUNTIME_USER}", "${POSTGRES_MONITORING_USER}";
SQL

psql -v ON_ERROR_STOP=1 --username "$POSTGRES_USER" --dbname "$POSTGRES_DB" <<SQL
CREATE EXTENSION IF NOT EXISTS pg_stat_statements;

GRANT USAGE ON SCHEMA public TO "${POSTGRES_RUNTIME_USER}";
GRANT SELECT, INSERT, UPDATE, DELETE ON ALL TABLES IN SCHEMA public TO "${POSTGRES_RUNTIME_USER}";
GRANT USAGE, SELECT, UPDATE ON ALL SEQUENCES IN SCHEMA public TO "${POSTGRES_RUNTIME_USER}";

ALTER DEFAULT PRIVILEGES FOR USER "${POSTGRES_DIRECT_USER}" IN SCHEMA public
  GRANT SELECT, INSERT, UPDATE, DELETE ON TABLES TO "${POSTGRES_RUNTIME_USER}";
ALTER DEFAULT PRIVILEGES FOR USER "${POSTGRES_DIRECT_USER}" IN SCHEMA public
  GRANT USAGE, SELECT, UPDATE ON SEQUENCES TO "${POSTGRES_RUNTIME_USER}";
SQL
